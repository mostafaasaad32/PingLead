export interface GenerateProposalInput {
  title: string;
  description: string;
  category?: string;
  platform?: string;
  freelancerBio?: string;
  freelancerSkills?: string | string[];
  toneOfVoice?: string;
  customInstructions?: string;
  portfolioItems?: PortfolioItem[];
  pricingHint?: string;
  standingInstructions?: string | null;
  writingSample?: string | null;
  pitchAngle?: 'direct' | 'action_plan' | 'snappy';
  refinementType?: 'shorten' | 'casual' | 'change_question';
  existingProposal?: string;
}

export interface GenerateProposalOutput {
  proposal: string;
  selectedPortfolio: ScoredPortfolioItem[];
  modelUsed: string;
  executionTimeMs: number;
  pitchAngle: string;
}

export async function generateContextAwareProposal(
  input: GenerateProposalInput
): Promise<GenerateProposalOutput> {
  const startTime = Date.now();
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is not configured in environment variables.');
  }

  // 1. Run context-aware portfolio selector to pick top 1-2 proof items
  const selectedPortfolio = selectBestPortfolioItems(
    {
      title: input.title,
      description: input.description,
      category: input.category || 'web_dev',
    },
    input.portfolioItems || [],
    2
  );

  const portfolioPromptContext = formatPortfolioForPrompt(selectedPortfolio);

  // 2. Profile context
  const skillsString = (Array.isArray(input.freelancerSkills) ? input.freelancerSkills.join(', ') : input.freelancerSkills || '').trim();
  const bio = (input.freelancerBio || '').trim();
  const replyLanguage = detectProjectLanguage(input.title, input.description);
  const tone = input.toneOfVoice || 'confident';
  const isKhamsat = (input.platform || '').toLowerCase().includes('khamsat');
  const angle = input.pitchAngle || 'direct';

  // 3. Build Pitch Angle instructions
  let angleInstruction = '';
  if (angle === 'action_plan') {
    angleInstruction = `
PITCH ANGLE: "ACTION PLAN 1-2-3"
- Diagnose the project need in line 1.
- Then present exactly 3 numbered, ultra-clear steps (1., 2., 3.) detailing how you will execute this cleanly.
- Weave the relevant portfolio item inside the relevant step.
- Finish with 1 sharp technical question.
`;
  } else if (angle === 'snappy') {
    angleInstruction = `
PITCH ANGLE: "SNAPPY (4 LINES MAX)"
- Deliver an ultra-dense, 4-line punchy proposal.
- Line 1: Hook on the exact issue.
- Line 2: The direct solution.
- Line 3: Weaved portfolio proof item with link.
- Line 4: The closing technical question.
`;
  } else {
    angleInstruction = `
PITCH ANGLE: "DIRECT + PORTFOLIO WEAVE (DEFAULT)"
- Line 1: Hook diagnosing the client's specific problem or requirement.
- Paragraph 2: Solution approach, with your matching portfolio item naturally woven into the sentence.
- Paragraph 3: Delivery / terms (if pricing guidance given).
- Closing: Exactly 1 sharp technical question.
`;
  }

  // 4. Build prompt based on regular generation vs refinement
  let promptText = '';

  if (input.refinementType && input.existingProposal) {
    let refinementInstruction = '';
    if (input.refinementType === 'shorten') {
      refinementInstruction = 'Shorten this proposal to roughly half its length while strictly keeping the core hook, the portfolio link, and the closing question. Make it ultra-punchy and direct.';
    } else if (input.refinementType === 'casual') {
      refinementInstruction = 'Rewrite this proposal to sound even more natural, conversational, and effortless, like a senior peer writing a quick helpful chat message. Eliminate any stiffness.';
    } else if (input.refinementType === 'change_question') {
      refinementInstruction = 'Keep the body of the proposal unchanged, but replace the closing question with a different, highly perceptive technical or scope question that compels the client to answer immediately.';
    }

    promptText = `
${STRICT_HUMAN_SYSTEM_INSTRUCTION}

TASK: REVISE AND REFINE THE FOLLOWING PROPOSAL
REFINEMENT OBJECTIVE: ${refinementInstruction}
REPLY LANGUAGE: ${replyLanguage === 'ar' ? 'Arabic' : 'English'}

ORIGINAL PROPOSAL:
"""
${input.existingProposal}
"""

PROJECT CONTEXT FOR REFERENCE:
- Title: ${input.title}
- Description: ${(input.description || '').slice(0, 1500)}

Output ONLY the revised refined proposal in plain text:
`.trim();
  } else {
    promptText = `
${STRICT_HUMAN_SYSTEM_INSTRUCTION}

${angleInstruction}

PROJECT CONTEXT:
- Platform: ${input.platform || 'Freelance Marketplace'}
- Category: #${input.category || 'general'}
- Title: ${input.title}
- Description & Requirements:
${(input.description || '').slice(0, 2000)}

REPLY LANGUAGE: ${replyLanguage === 'ar' ? 'Arabic' : 'English'}

FREELANCER PROFILE:
- Bio: ${bio || 'not provided'}
- Skills: ${skillsString || 'not provided'}
- Tone: ${tone}
${input.customInstructions ? `- Custom Instructions: ${input.customInstructions}` : ''}
${input.standingInstructions?.trim() ? `- Freelancer Standing Instructions (ALWAYS follow these): ${input.standingInstructions.trim().slice(0, 1000)}` : ''}
${input.writingSample?.trim() ? `
STYLE CLONING (MATCH THIS HUMAN FREELANCER'S PERSONAL WRITING STYLE):
The freelancer wrote this real proposal previously. Match its rhythm, sentence length, vocabulary simplicity, and authentic tone:
"""
${input.writingSample.trim().slice(0, 1200)}
"""
` : ''}
${isKhamsat ? `
SPECIAL KHAMSAT COMMUNITY DIRECTIVE:
* This is posted in Khamsat community requests ("طلبات الخدمات غير الموجودة").
* Keep it to 3-4 punchy lines ready for immediate execution, mentioning ordering through your service.
` : ''}
${input.pricingHint ? `PRICING GUIDANCE (REQUIRED):\n${input.pricingHint}\nInclude one plain sentence with your price and delivery time before the closing question.\n` : ''}
${portfolioPromptContext}

Write the human proposal now (plain text only, zero markdown symbols):
`.trim();
  }

  // 4. Try candidate Gemini models with fallback
  let generatedProposal = '';
  let successfulModel = '';

  for (const model of CANDIDATE_MODELS) {
    try {
      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
      const res = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [
            {
              parts: [{ text: promptText }],
            },
          ],
          generationConfig: {
            // Some variety between proposals: identical structure is what gives AI text away
            temperature: 0.7,
            maxOutputTokens: 1000,
          },
        }),
        signal: AbortSignal.timeout(25000),
      });

      if (!res.ok) {
        console.warn(`[AI Proposal Generator] Model ${model} returned HTTP ${res.status}, trying fallback...`);
        continue;
      }

      const data = await res.json();
      const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
      if (text && text.trim().length > 30) {
        generatedProposal = cleanProposalText(text);
        successfulModel = model;
        break;
      }
    } catch (err: any) {
      console.warn(`[AI Proposal Generator] Exception with ${model}:`, err.message);
    }
  }

  if (!generatedProposal) {
    throw new Error('Failed to generate proposal across all candidate Gemini models.');
  }

  return {
    proposal: generatedProposal,
    selectedPortfolio,
    modelUsed: successfulModel,
    executionTimeMs: Date.now() - startTime,
    pitchAngle: angle,
  };
}

/** 'ar' when the project itself is mostly Arabic, otherwise 'en' (the reply follows the project). */
export function detectProjectLanguage(title?: string | null, description?: string | null): 'ar' | 'en' {
  const text = `${title || ''} ${(description || '').slice(0, 1500)}`;
  const arabic = (text.match(/[؀-ۿ]/g) || []).length;
  const latin = (text.match(/[A-Za-z]/g) || []).length;
  return arabic > 0 && arabic >= latin * 0.5 ? 'ar' : 'en';
}

/**
 * Makes the model's output safe to paste into a plain marketplace text box: strips markdown,
 * turns [text](url) into the url, removes leftover placeholders like "[حدد المدة]".
 */
export function cleanProposalText(raw: string): string {
  let t = raw.replace(/\r/g, '').trim();
  t = t.replace(/^```[a-z]*\n?|```$/gim, '');
  t = t.replace(/\[([^\]\n]*)\]\((https?:\/\/[^)\s]+)\)/g, (_m, label: string, url: string) =>
    !label || label.trim() === url || /^https?:/.test(label.trim()) ? url : `${label.trim()}: ${url}`
  );
  t = t.replace(/\*\*|__/g, '');
  t = t.replace(/^#{1,6}\s*/gm, '');
  // Template section titles on their own line ("خطة العمل:", "Roadmap:")
  t = t.replace(/^\s*(?:خطة العمل|خارطة الطريق|خارطة العمل|طريقة التنفيذ|Roadmap|My approach|Plan|Approach)\s*:?\s*$/gim, '');
  t = t.replace(/^\s*[*•]\s+/gm, '- ');
  // Bracketed placeholders (not links): "[حدد المدة]", "[X days]", "[اسمك]"
  t = t.replace(/\s*\[[^\]\n]{1,40}\]/g, '');
  t = t.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n');
  return t.trim();
}
